#!/usr/bin/env python3
"""Exact original-source tests of the three-channel factorial identity.

The physical columns are generated by the original coproduct, independently
of the proposed positive sum. Finite tests do not prove the all-level identity.
"""
import itertools
import json
from pathlib import Path

import numpy as np

from audit_actual_two_cut_ports import balanced_data, coproduct


def case(N):
    p, eta, q, E, F, K, pivot, R, Ri = balanced_data(N)
    d, m, Q, x = N-1, (N-1)//2, q*q % p, pow(q, N-1, p)
    rho = (q-pow(q, -1, p)) % p
    Et, Ft, Kt = coproduct(rho*rho*E % p, F, K, 2, N, p)
    qb, Qb, xb = pow(q, -1, p), pow(Q, -1, p), pow(x, -1, p)
    Eb = np.diag([(pow(Qb, -a, p)-1) % p for a in range(1, N)], 1)
    Fb = np.diag([(1-pow(Qb, a, p)) % p for a in range(1, N)], -1)
    Kb = np.diag([xb*pow(Qb, -a, p) % p for a in range(N)])
    Ebt, Fbt, Kbt = coproduct(Eb, Fb, Kb, 2, N, p)
    fac, facb, sine = [1], [1], [1]
    imag = pow(eta, N, p)
    for r in range(1, N):
        fac.append(fac[-1]*(1-pow(Q, r, p)) % p)
        facb.append(facb[-1]*(1-pow(Qb, r, p)) % p)
        sine.append(pow(imag, r, p)*pow(q, -r*(r+1)//2, p)*fac[r] % p)

    columns, bars = {}, {}
    for j in range(m+1):
        h = d-j
        pair = []
        for q0, Q0, ff, lowering, raising in (
                (q, Q, fac, Ft, Et), (qb, Qb, facb, Fbt, Ebt)):
            W = np.zeros((N*N, 2*j+1), dtype=np.int64)
            for a in range(h+1):
                W[a*N+h-a, 0] = pow(q0, a*a, p)*ff[h]*pow(ff[a]*ff[h-a], -1, p) % p
            assert not np.any(raising@W[:, 0] % p)
            for r in range(1, 2*j+1):
                W[:, r] = lowering@W[:, r-1] % p * pow(1-pow(Q0, r, p), -1, p) % p
            assert not np.any(lowering@W[:, -1] % p)
            # General all-label endpoint formula, not just odd Steinberg.
            ell = pow(q0, j*(d-2*j), p)
            for a in range(h+1):
                assert W[(j+a)*N+d-a, 2*j] == ell*int(W[a*N+h-a, 0]) % p
            assert W[d, j] == pow(q0, -j*j, p)
            pair.append(W)
        columns[j], bars[j] = pair

    supported = vanished = 0
    for a, b, c in itertools.product(range(m+1), repeat=3):
        r = b+c-a
        if not 0 <= r <= 2*b:
            continue
        J = a+b+c
        # Literal black cup coefficient, original pair exchange and N^3 cups.
        # Here k=d-physical_first; no Racah normalization is used on this side.
        raw = 0
        for k in range(min(d-a, d-c)+1):
            first = int(bars[a][(a+k)*N+d-k, 2*a])
            second = int(bars[b][(c+k)*N+d-a-k, r])
            third = int(bars[c][k*N+d-c-k, 0])
            raw += pow(x, k+a+c-2*d, p)*first*second*third
        actual = raw % p
        if J < d:
            assert actual == 0, (N, a, b, c, 'support')
            vanished += 1
            continue
        delta = J-d
        positive = 0
        for t in range(max(a, b, c), min(a+b, a+c, b+c)+1):
            den = (sine[t-a]*sine[t-b]*sine[t-c]*sine[d+t-J]
                   *sine[a+b-t]*sine[a+c-t]*sine[b+c-t]) % p
            positive += sine[t]*pow(den, -1, p)
        positive = N*positive % p
        normalizer = sine[a]*sine[b]*sine[c]*pow(N*sine[delta], -1, p) % p
        phase = 2*a*a-a*b-a*c+b*c-J-3
        target = (-1)**(N+J)*pow(q, phase, p)*normalizer*positive % p
        assert actual == target, (N, a, b, c, actual, target)
        supported += 1
    return {'N': N, 'prime': p, 'actual_coproduct_columns': True,
            'all_label_highest_lowest_middle_endpoints': True,
            'full_source_scalar_supported_triples': supported,
            'full_source_scalar_vanishing_triples': vanished,
            'candidate_phase_and_seven_factorial_sum': True}


if __name__ == '__main__':
    rows = [case(N) for N in range(2, 17)]
    out = {'status': 'PASS', 'original_source_levels': rows,
           'scope': 'Exact finite tests of the original trivalent highest-corner coefficient and general factorial identity. The all-level finite transformation is proved separately in the square-linearization and Euler/Racah notes; finite tests alone do not prove it. No full vertex norm, general marked graph survival, or hyperbolic-volume equality is asserted by this audit.'}
    Path(__file__).with_name('actual_trivalent_general_scalar_candidate_results.json').write_text(json.dumps(out, indent=2)+'\n')
    print('PASS', len(rows), 'original levels;', sum(r['full_source_scalar_supported_triples'] for r in rows),
          'supported and', sum(r['full_source_scalar_vanishing_triples'] for r in rows), 'vanishing triangle triples')
